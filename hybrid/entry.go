package hybrid

import (
	"GopherAI/config"
	"GopherAI/entry"
	"context"
	"errors"
	"github.com/BurntSushi/toml"
	"github.com/xiaopang456/GopherLearn/conversation"
	"net"
	"net/http"
	"time"
)

type entrySettings struct {
	v2 *entry.Settings
}

// retiredOrdinaryChatSection explains, in one printable sentence, why the section is
// refused rather than ignored. It is worded for an operator who has the old file open:
// name the section, say what took its job, say what to do.
const retiredOrdinaryChatSection = "retired configuration setting: [ordinaryChat] was removed. " +
	"A conversation turn is now generated by the learning Agent's chat model, the one this " +
	"deployment already configures under [isolatedEntry] for the address, model and key it " +
	"calls, so no second client is built from [ordinaryChat] and its context and summary " +
	"settings are not read either. Delete the [ordinaryChat] section."

func loadEntry(path string) (*entrySettings, error) {
	v2, err := entry.Load(path)
	if err != nil {
		return nil, err
	}
	// This executable is not a migration command. Do not inherit the native
	// entry's optional migration flag, including when explicitly set to true.
	if v2.Entry.Migrate {
		return nil, config.Refusef("hybrid entry refuses business migration")
	}
	// The section is looked for by decoding it into a pointer: its presence is the fact,
	// and an empty-but-written section is still a section the operator believes is in
	// force. Refusing it by name rather than skipping past it is deliberate - a file that
	// configures a client nobody constructs reads as one that still does.
	var sections struct {
		Ordinary *map[string]string `toml:"ordinaryChat"`
	}
	if _, err := toml.DecodeFile(path, &sections); err != nil {
		return nil, err
	}
	if sections.Ordinary != nil {
		return nil, config.Refusef("%s", retiredOrdinaryChatSection)
	}
	return &entrySettings{v2: v2}, nil
}

type entryRuntime struct {
	dependencies    func(*entry.Settings) entry.Dependencies
	listen          func(string, string) (net.Listener, error)
	server          func(string, http.Handler) *http.Server
	shutdownTimeout time.Duration
}

// Run loads only an explicitly named independent file. Production factories
// are reached only after both native and ordinary configuration validation.
func Run(ctx context.Context, path string) error {
	return runEntry(ctx, path, entryRuntime{entry.ProductionDependencies, net.Listen, entry.NewHTTPServer, 15 * time.Second})
}

func runEntry(ctx context.Context, path string, runtime entryRuntime) (result error) {
	settings, err := loadEntry(path)
	if err != nil {
		return err
	}
	if runtime.dependencies == nil || runtime.listen == nil || runtime.server == nil || runtime.shutdownTimeout <= 0 {
		return errors.New("incomplete hybrid entry factories")
	}
	if err := ctx.Err(); err != nil {
		return err
	}
	// No ordinary model: a conversation turn is generated by the Agent's own chat model,
	// assembled from [isolatedEntry] below. Nil here is the production shape, and
	// Assemble reads it as "this build carries one engine".
	app, err := Assemble(context.Background(), settings.v2, runtime.dependencies(settings.v2), nil, conversation.Options{})
	if err != nil {
		return err
	}
	defer func() { result = errors.Join(result, app.Close()) }()
	if err := ctx.Err(); err != nil {
		return err
	}
	server := runtime.server(settings.v2.Address(), app.Handler)
	if server == nil {
		return errors.New("nil hybrid HTTP server")
	}
	listener, err := runtime.listen("tcp", settings.v2.Address())
	if err != nil {
		return err
	}
	if listener == nil {
		return errors.New("nil hybrid listener")
	}
	serveErrors := make(chan error, 1)
	go func() { serveErrors <- server.Serve(listener) }()
	var serveErr error
	var received bool
	select {
	case <-ctx.Done():
	case serveErr = <-serveErrors:
		received = true
	}
	shutdownCtx, cancel := context.WithTimeout(context.Background(), runtime.shutdownTimeout)
	defer cancel()
	shutdownErr := server.Shutdown(shutdownCtx)
	if shutdownErr != nil {
		shutdownErr = errors.Join(shutdownErr, server.Close())
	}
	if !received {
		serveErr = <-serveErrors
	}
	if errors.Is(serveErr, http.ErrServerClosed) {
		serveErr = nil
	}
	return errors.Join(serveErr, shutdownErr)
}
