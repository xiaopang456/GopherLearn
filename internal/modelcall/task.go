// Purpose names why a model call was made, as decided by the server code that
// made it. It is never inferred from user text: a question that mentions
// summarising does not turn a dialogue call into a summary call.
type Purpose string

const (
	// PurposeDialogue is the call that answers the user's turn, including every
	// decision round inside an agent turn.
	PurposeDialogue Purpose = "dialogue"
	// PurposeSummary is the rolling-summary refresh that happens before an answer
	// exists. It is a real model call and it is not part of the answer's token
	// count unless it is added on purpose.
	PurposeSummary Purpose = "summary"
	// PurposeQuizGeneration is one attempt at writing a question set, including the
	// attempts that were rejected by the server's own shape rules.
	PurposeQuizGeneration Purpose = "quiz_generation"
	// PurposeQuizGrading is one attempt at scoring one answer.
	PurposeQuizGrading Purpose = "quiz_grading"
	// PurposeEpisodeProjection is one background attempt at projecting a
	// finished conversation into its episodic-memory card. It runs outside any
	// user turn, which is exactly why it carries its own label: a projection's
	// tokens must never be read as part of the answer's or the summary's cost.
	PurposeEpisodeProjection Purpose = "episode_projection"
	// PurposeEpisodeVerification is the support verifier's second-opinion call
	// on one proposed assertion. It is labelled apart from the projection so
	// the two layers' costs can be told apart.
	PurposeEpisodeVerification Purpose = "episode_verification"
	// PurposeUnlabelled is a call that reached the model outside any labelled
	// phase. It exists so an unlabelled call shows up as a gap rather than
	// silently borrowing another phase's total.
	PurposeUnlabelled Purpose = "unlabelled"
)

type purposeKey struct{}

// WithPurpose labels every model call made from ctx downstream. Nested uses each
// get their own label, and a task that never sets one is recorded as unlabelled.
func WithPurpose(ctx context.Context, purpose Purpose) context.Context {
	if ctx == nil || purpose == "" {
		return ctx
	}
	return context.WithValue(ctx, purposeKey{}, purpose)
}

// PurposeFromContext returns the label in force on ctx, or unlabelled.
func PurposeFromContext(ctx context.Context) Purpose {
	if ctx == nil {
		return PurposeUnlabelled
	}
	purpose, ok := ctx.Value(purposeKey{}).(Purpose)
	if !ok || purpose == "" {
		return PurposeUnlabelled
	}
	return purpose
}

// TaskRecord is the single line one user operation leaves behind.
//
// It is a measurement record, not a business fact: nothing about an answer, a
// grade or a permission is decided from it. The fields that a given operation
// cannot produce are pointers so they serialise as null rather than as a zero
// that reads like a measurement of nothing.
type TaskRecord struct {
	// TaskID is generated by this process and is not derived from user input.
	TaskID string `json:"task_id"`
	// Operation is the server-chosen name of the user operation.
	Operation string `json:"operation"`
	// Outcome classifies how the operation ended.
	Outcome Outcome `json:"outcome"`
	// FailureStage names where it stopped, from a controlled list. The error text
	// itself is never stored: a provider message can echo the prompt.
	FailureStage string `json:"failure_stage,omitempty"`
	// ReasonCode is the controlled classification of the cause.
	ReasonCode string `json:"reason_code,omitempty"`

	// DurationMillis is the server-side operation span: from the moment the
	// service method started this task to the moment Seal reads the clock. That
	// read is the first thing Seal does, so the call snapshot, the roll-up and the
	// synchronous sink write that follow are excluded - this number does not
	// include the observation's own tail. Nor is it client end-to-end latency: it
	// starts after HTTP arrival, authentication and request-body parsing, and it
	// stops before the handler keeps writing the response.
	DurationMillis int64 `json:"duration_millis"`
	// FirstEventMillis is the offset from the operation start to the first stream
	// frame that was successfully written out. Null for an operation that streams
	// nothing.
	FirstEventMillis *int64 `json:"first_event_millis"`
	// FirstTextMillis is the offset to the first non-empty public text that was
	// successfully written out. On an agent turn that may be a block of decision
	// narration rather than the answer, which is what FirstTextIsFinalAnswer says.
	// It is never a claim about answer TTFT by itself.
	FirstTextMillis *int64 `json:"first_text_millis"`
	// FirstTextIsFinalAnswer reports whether that first text belonged to the block
	// the turn finally confirmed as its answer. False with a non-null
	// FirstTextMillis means the first thing the learner saw was not the answer.
	FirstTextIsFinalAnswer bool `json:"first_text_is_final_answer"`

	// AnswerStored and Delivered are separated on purpose: an answer that was
	// written to the store while the terminal frame failed to leave the process is
	// neither a full success nor a lost turn. Null means the operation has no
	// such step.
	AnswerStored *bool `json:"answer_stored"`
	Delivered    *bool `json:"delivered"`

	// Cost stays "unknown" while this repository has no price source and while
	// embedding and rerank calls are unmetred. Nothing should read a token total
	// here and multiply it into a claimed cost.
	Cost string `json:"cost"`

	// Calls are the individual model calls, in the order they were issued, each
	// carrying its purpose and sequence number.
	Calls []Call `json:"calls"`
	// Totals is the whole-task roll-up; Totals.ByPurpose breaks it down per phase.
	Totals Totals `json:"totals"`
}

// PurposeTotals is the roll-up of one labelled phase.
type PurposeTotals struct {
	Calls      int          `json:"calls"`
	Dispatches int          `json:"dispatches"`
	Status     TotalsStatus `json:"status"`
	Prompt     Sum          `json:"prompt"`
	Completion Sum          `json:"completion"`
	Total      Sum          `json:"total"`
	Cached     Sum          `json:"cached"`
}

// Sink consumes one finished task record. Returning an error only reports that
// the record could not be written; it never changes the business outcome.
type Sink func(TaskRecord) error

// Publisher decides whether task metering is on, hands out task scopes, and
// writes the one record each task produces.
//
// It holds no per-task accumulation: every task gets its own Collector, so two
// concurrent operations cannot add into each other's totals. The only shared
// state is the failure signal - counters, and a controlled category for the last
// write that failed - which exists so a broken sink is visible instead of silent.
type Publisher struct {
	enabled bool
	sink    Sink
	now     func() time.Time

	seq       atomic.Uint64
	published atomic.Uint64
	failed    atomic.Uint64

	// lastFailureMu guards a fixed category string, never an error text.
	lastFailureMu sync.Mutex
	lastFailure   string
}

// NewPublisher builds a publisher. A disabled publisher behaves as if the
// feature were compiled out: Start returns no handle and every handle method is a
// no-op.
func NewPublisher(enabled bool, sink Sink) *Publisher {
	return &Publisher{enabled: enabled, sink: sink, now: time.Now}
}

// WithClock lets a test own the timestamps.
func (p *Publisher) WithClock(now func() time.Time) *Publisher {
	if p != nil && now != nil && p.now != nil {
		p.now = now
	}
	return p
}

// Enabled reports whether task records are being produced at all.
func (p *Publisher) Enabled() bool { return p != nil && p.enabled }

// PublisherStats is the observable signal for sink health.
type PublisherStats struct {
	Published   uint64 `json:"published"`
	Failed      uint64 `json:"failed"`
	LastFailure string `json:"last_failure"`
}

// Stats reports how many records were written and how many failed to be.
func (p *Publisher) Stats() PublisherStats {
	if p == nil {
		return PublisherStats{}
	}
	p.lastFailureMu.Lock()
	defer p.lastFailureMu.Unlock()
	return PublisherStats{
		Published:   p.published.Load(),
		Failed:      p.failed.Load(),
		LastFailure: p.lastFailure,
	}
}

// Start opens one task scope and returns the context that carries it, plus a
// handle that is nil when metering is off or the publisher is missing. A nil
// handle accepts every call below, so the instrumented code has one path.
func (p *Publisher) Start(ctx context.Context, operation string) (context.Context, *TaskHandle) {
	if !p.Enabled() || ctx == nil {
		return ctx, nil
	}
	collector := New().withClock(p.now)
	taskID := p.nextTaskID(operation)
	handle := &TaskHandle{
		publisher: p,
		collector: collector,
		started:   p.now(),
		record: TaskRecord{
			TaskID:    taskID,
			Operation: operation,
			Cost:      "unknown",
		},
	}
	// The collector goes on the context next to the task, because that is what a
	// model call looks for. Without this line the task would seal into one empty
	// record while every call it caused was measured nowhere.
	ctx = WithCollector(ctx, collector)
	return withRecord(ctx, &record{task: handle}), handle
}

func (p *Publisher) nextTaskID(operation string) string {
	// Sequence plus the process's view of "now": unique within a process without
	// needing a durable id source, and never derived from anything a user typed.
	return operation + "-" + itoa(p.seq.Add(1)) + "-" + itoa(uint64(p.now().UnixNano()))
}

// Failure is what the operation actually hit, before the service mapped it into
// the error its caller is supposed to see. It is recorded separately from the
// seal arguments precisely because that mapping exists: a store fault and an
// unavailable model both leave as ErrInternal, and a record that repeated the
// outward value would say nothing.
type Failure struct {
	Outcome Outcome
	Stage   string
	Reason  string
}

// TaskHandle is one operation under measurement. Sealed exactly once.
type TaskHandle struct {
	publisher *Publisher
	collector *Collector
	started   time.Time

	// failure keeps the first cause the caller noted. Later notes - a failed
	// delivery of the failure notice itself - must not replace it.
	failure *Failure

	mu     sync.Mutex
	record TaskRecord
	sealed bool
	// firstTextBlock remembers which published block the first visible text came
	// from, so the final answer comparison can be made at seal time.
	firstTextBlock     string
	sawFirstText       bool
	confirmedBlockSeen bool
}

// Collector returns the per-task collector, which is what puts model calls inside
// this task and no other.
func (h *TaskHandle) Collector() *Collector {
	if h == nil {
		return nil
	}
	return h.collector
}

// NoteFirstEvent records the offset of a stream frame that was written out
// successfully. Only the first one counts.
func (h *TaskHandle) NoteFirstEvent() {
	if h == nil {
		return
	}
	h.mu.Lock()
	defer h.mu.Unlock()
	if h.record.FirstEventMillis == nil {
		value := millisSince(h.started, h.publisher.now())
		h.record.FirstEventMillis = &value
	}
}

// NoteFirstText records the offset of the first non-empty public text that was
// written out successfully, and which block it belonged to ("" for the plain
// answer channel, which has no blocks).
func (h *TaskHandle) NoteFirstText(blockID string) {
	if h == nil {
		return
	}
	h.mu.Lock()
	defer h.mu.Unlock()
	if h.sawFirstText {
		return
	}
	value := millisSince(h.started, h.publisher.now())
	h.record.FirstTextMillis = &value
	h.firstTextBlock = blockID
	h.sawFirstText = true
}

// NoteConfirmedBlock names the block the turn confirmed as its answer, known
// only once the turn has one. Callers may note it before sealing.
func (h *TaskHandle) NoteConfirmedBlock(blockID string) {
	if h == nil {
		return
	}
	h.mu.Lock()
	defer h.mu.Unlock()
	h.confirmedBlockSeen = true
	h.record.FirstTextIsFinalAnswer = h.sawFirstText && blockID == h.firstTextBlock
}

// NoteAnswerStored separates "the row exists" from "the client saw the end".
func (h *TaskHandle) NoteAnswerStored(stored bool) {
	if h == nil {
		return
	}
	h.mu.Lock()
	defer h.mu.Unlock()
	value := stored
	h.record.AnswerStored = &value
}

// NoteDelivered says whether the terminal frame left the process.
func (h *TaskHandle) NoteDelivered(delivered bool) {
	if h == nil {
		return
	}
	h.mu.Lock()
	defer h.mu.Unlock()
	value := delivered
	h.record.Delivered = &value
}

// NoteFailure records the cause of this operation. Only the first note is kept,
// so a second failure further down the same path - typically the failure notice
// itself being unwritable - cannot erase the first one from the record.
func (h *TaskHandle) NoteFailure(failure Failure) {
	if h == nil || failure.Outcome == "" {
		return
	}
	h.mu.Lock()
	defer h.mu.Unlock()
	if h.failure == nil {
		noted := failure
		h.failure = &noted
	}
}

// DeliveryFailed reports whether a terminal write was attempted and could not
// leave the process. A caller that turns that into its own generic error still
// needs the measurement to say which failure it really was.
func (h *TaskHandle) DeliveryFailed() bool {
	if h == nil {
		return false
	}
	h.mu.Lock()
	defer h.mu.Unlock()
	return h.record.Delivered != nil && !*h.record.Delivered
}

// Seal finishes the task, builds the totals from this task's own collector, and
// writes exactly one record. Later seals do nothing, so a deferred safety net
// cannot duplicate the line.
func (h *TaskHandle) Seal(outcome Outcome, failureStage, reasonCode string) {
	if h == nil {
		return
	}
	h.mu.Lock()
	if h.sealed {
		h.mu.Unlock()
		return
	}
	h.sealed = true
	// The noted cause wins: the caller records what really happened before it
	// returns the mapped error, and the deferred seal below must not overwrite
	// that with the generic value the caller receives.
	if h.failure != nil {
		outcome, failureStage, reasonCode = h.failure.Outcome, h.failure.Stage, h.failure.Reason
	}
	if outcome == "" {
		outcome = OutcomeOther
	}
	h.record.Outcome = outcome
	h.record.FailureStage = failureStage
	h.record.ReasonCode = reasonCode
	// Read the clock before anything that produces the record: the snapshot, the
	// roll-up and the synchronous sink write below are the observation's own cost,
	// and charging them to the operation would measure the meter instead.
	h.record.DurationMillis = millisSince(h.started, h.publisher.now())
	h.record.Calls = h.collector.Snapshot()
	h.record.Totals = totalsOf(h.record.Calls)
	publisher := h.publisher
	record := h.record
	h.mu.Unlock()

	publisher.write(record)
}

func (p *Publisher) write(record TaskRecord) {
	if p.sink == nil {
		p.countFailure("sink_missing")
		return
	}
	defer func() {
		// A sink that panics is a logging bug, and a logging bug must not end a
		// learner's turn.
		if recovered := recover(); recovered != nil {
			p.countFailure("sink_panic")
		}
	}()
	if err := p.sink(record); err != nil {
		p.countFailure("sink_error")
		return
	}
	p.published.Add(1)
}

func (p *Publisher) countFailure(category string) {
	p.failed.Add(1)
	p.lastFailureMu.Lock()
	defer p.lastFailureMu.Unlock()
	p.lastFailure = category
}

// NewJSONSink writes one JSON object per task record to w.
//
// The mutex is not decoration. A shared json.Encoder keeps a sticky error field,
// so two concurrent writes on a failing writer race on it - one goroutine can read
// another's error, and an interleaved pair of records is worse than either. Encode
// and its lock are released by defer even when the writer panics, so a bad sink
// cannot wedge the process either.
func NewJSONSink(w io.Writer) Sink {
	if w == nil {
		return nil
	}
	var mu sync.Mutex
	encoder := json.NewEncoder(w)
	return func(record TaskRecord) error {
		mu.Lock()
		defer mu.Unlock()
		return encoder.Encode(record)
	}
}

// record is what a nested call looks up to find the task it belongs to. It is
// kept in a private type so no other package can forge a task association by
// guessing a context key.
type record struct{ task *TaskHandle }

type recordKey struct{}

func withRecord(ctx context.Context, record *record) context.Context {
	return context.WithValue(ctx, recordKey{}, record)
}

// CurrentTask returns the handle for the task this context belongs to, so a
// deeper helper can note a timing without threading a parameter through every
// signature. A call outside any task scope gets nil, which is inert.
func CurrentTask(ctx context.Context) *TaskHandle {
	if ctx == nil {
		return nil
	}
	value, ok := ctx.Value(recordKey{}).(*record)
	if !ok || value == nil {
		return nil
	}
	return value.task
}

func itoa(value uint64) string {
	if value == 0 {
		return "0"
	}
	var digits [20]byte
	index := len(digits)
	for value > 0 {
		index--
		digits[index] = byte('0' + value%10)
		value /= 10
	}
	return string(digits[index:])
}
